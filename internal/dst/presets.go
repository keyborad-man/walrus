func PresetLuaByID(id string, shard string) string {
	for _, p := range BuiltinPresets {
		if p.ID == id {
			return p.Lua
		}
	}
	if shard == "caves" {
		return BuiltinPresets[len(BuiltinPresets)-1].Lua
	}
	return BuiltinPresets[0].Lua
}
